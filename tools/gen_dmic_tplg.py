#!/usr/bin/env python3
"""Generate kext/LatSOFAudio/tplg_ipc_dmic4ch.h from a bpftrace dump of sof_ipc_tx_message.

  python3 -I tools/gen_dmic_tplg.py current/ipc-boot.txt > kext/LatSOFAudio/tplg_ipc_dmic4ch.h

Takes the LAST capture sequence of the 4ch DMIC pipeline (PIPE_NEW ... PIPE_COMPLETE of the pipeline
that ends in PCM_PARAMS with 4 channels) and emits it verbatim. DAI_CONFIG is left as a placeholder
(len 0) because the driver builds it itself.
"""
import re, struct, sys

def parse(s):
    # bpftrace %r: non-printables as \\xNN, printable (including '\\') as-is
    out = bytearray(); i = 0
    while i < len(s):
        if s[i] == '\\' and s[i+1:i+2] == 'x' and re.fullmatch(r'[0-9a-fA-F]{2}', s[i+2:i+4]):
            out.append(int(s[i+2:i+4], 16)); i += 4
        else:
            out.append(ord(s[i])); i += 1
    return bytes(out)

msgs = []
for line in open(sys.argv[1], encoding='latin1'):
    m = re.match(r't=(\d+) len=(\d+) (.*)$', line.rstrip('\n'))
    if m:
        b = parse(m[3]); n = int(m[2])
        assert len(b) == min(n, 256), (n, len(b), line[:80])
        msgs.append(b)

cmd = lambda b: struct.unpack_from('<I', b, 4)[0]
# last PCM_PARAMS with channels == 4, then walk back to its PIPE_NEW
pp = [i for i, b in enumerate(msgs) if cmd(b) == 0x60010000 and struct.unpack_from('<H', b, 74)[0] == 4][-1]
start = max(i for i in range(pp) if cmd(msgs[i]) == 0x30100000)
seq = msgs[start:pp]
names = {0x30100000: 'PIPE_NEW', 0x30010000: 'COMP_NEW', 0x30200000: 'BUF_NEW', 0x30030000: 'CONNECT',
         0x30130000: 'PIPE_COMPLETE', 0x80010000: 'DAI_CONFIG'}
ids = {}
print('// Generated by tools/gen_dmic_tplg.py from a Linux (Ubuntu, sof-cml.ri 2:2:0-57864, ABI 3:22:1)')
print('// bpftrace dump of sof_ipc_tx_message: topology objects of the 4ch DMIC capture pipeline')
print('// (PIPELINE.10.DMIC0.IN), in the order Linux sends them. Do not edit by hand.')
print('// SPDX-License-Identifier: BSD-3-Clause')
print()
first = struct.unpack_from('<IIIII', seq[0], 0)
print(f'#define DMIC4CH_PIPE_SCHED_ID {first[2]}   // PIPE_NEW comp_id')
print(f'#define DMIC4CH_PIPE_ID       {first[3]}')
print(f'#define DMIC4CH_PIPE_DAI_ID   {first[4]}   // PIPE_NEW sched_id: the DAI schedules a capture pipeline')
host = [b for b in seq if cmd(b) == 0x30010000 and struct.unpack_from('<I', b, 12)[0] == 1]
print(f'#define DMIC4CH_HOST_ID       {struct.unpack_from("<I", host[0], 8)[0] if host else -1}   // COMP_NEW type=host')
print()
print('struct DmicTplgMsg { UInt32 len; const UInt8 *data; };')
print()
for k, b in enumerate(seq):
    c = cmd(b)
    if c == 0x80010000:
        continue
    print(f'static const UInt8 kDmicMsg{k}[] = {{ ' + ', '.join(f'0x{x:02x}' for x in b) + f' }}; // {names.get(c, hex(c))}')
print()
print('static const struct DmicTplgMsg kDmicTplg[] = {')
for k, b in enumerate(seq):
    c = cmd(b)
    if c == 0x80010000:
        print(f'    {{ 0, nullptr }},   // [{k}] DAI_CONFIG (built by the driver)')
    else:
        print(f'    {{ {len(b)}, kDmicMsg{k} }},   // [{k}] {names.get(c, hex(c))}')
print('};')
print(f'static const int kDmicTplgCount = {len(seq)};')

